import assert from 'node:assert/strict';
import { db } from '../server/dist/db.js';
import { createBot } from '../server/dist/bots.js';
import { toolMap } from '../server/dist/agent/tools.js';
import { initSubagents } from '../server/dist/agent/subagents.js';
import { listBots } from '../server/dist/store.js';
initSubagents();
db.prepare('INSERT INTO users(id,email,name,created_at) VALUES (?,?,?,?)').run('owner','owner@example.com','Owner',Date.now());
db.prepare('INSERT INTO users(id,email,name,created_at) VALUES (?,?,?,?)').run('other','other@example.com','Other',Date.now());
const chief=createBot('owner',{name:'Chief',isPrimary:true});
const teammate=createBot('owner',{name:'Existing'});
db.prepare("UPDATE bots SET agent_provider='claude',model='sonnet' WHERE id=?").run(chief.id);
const tool=toolMap.get('create_bot');assert.ok(tool);
const messages=[];
const request='Create a new research bot named Nova and ask it to compare three cameras.';
const ctx={userId:'owner',botId:chief.id,depth:0,directUserRequest:request,enqueueBotMessage:(...args)=>messages.push(args)};
const args={name:'Nova',role:'Researcher',task:'Compare three cameras and report results to Chief.',request_quote:request};
const count=()=>db.prepare('SELECT COUNT(*) n FROM bots').get().n;
const initial=count();
const helper=toolMap.get('spawn_subagent');
for (const source of [{directUserRequest:undefined},{botId:teammate.id},{depth:1}]) {
  const result=await helper.impl({goal:'Do not create'}, {...ctx,...source});
  assert.match(result.output,/Only the primary/);
}
assert.equal(count(),initial);
await assert.rejects(()=>tool.impl(args,{...ctx,botId:teammate.id}),/primary/);
await assert.rejects(()=>tool.impl(args,{...ctx,userId:'other'}),/primary/);
for (const source of [{directUserRequest:undefined},{depth:1},{directUserRequest:'Different request'}]) await assert.rejects(()=>tool.impl(args,{...ctx,...source}));
await assert.rejects(()=>tool.impl({...args,name:''},ctx));
assert.equal(count(),initial);assert.equal(messages.length,0);
const result=JSON.parse((await tool.impl(args,ctx)).output);
assert.equal(result.created,true);assert.equal(count(),initial+1);
assert.ok(listBots('owner').some(b=>b.id===result.bot_id),'Created bot is visible in the sidebar roster');
assert.ok(!listBots('other').some(b=>b.id===result.bot_id));
const bot=db.prepare('SELECT * FROM bots WHERE id=?').get(result.bot_id);
assert.equal(bot.is_primary,0);assert.equal(bot.agent_provider,'claude');assert.equal(bot.model,'sonnet');
assert.match(bot.instructions,/send_to_bot/);
const task=db.prepare('SELECT * FROM tasks WHERE id=?').get(result.task_id);
assert.equal(task.bot_id,result.bot_id);assert.equal(task.state,'working');
assert.equal(messages.length,1);assert.equal(messages[0][1],result.bot_id);assert.match(messages[0][2],/Compare three cameras/);
const duplicate=JSON.parse((await tool.impl(args,ctx)).output);
assert.equal(duplicate.created,false);assert.equal(count(),initial+1);assert.equal(messages.length,1);
console.log('PASS: primary-only direct-user creation, ownership, request quote, validation, visible roster, inherited provider, task dispatch and duplicate prevention');
db.close();
